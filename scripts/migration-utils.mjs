import { execFileSync } from 'node:child_process';
import { readdirSync } from 'node:fs';

export const providers = ['sqlite', 'postgresql'];
export const baseline = '00000000000000_init';
export function prisma(args, env = process.env) {
  return execFileSync('pnpm', ['exec', 'prisma', ...args], { env, encoding: 'utf8', stdio: ['pipe', 'pipe', 'inherit'] });
}

// pg_trgm is optional on managed/restricted installations. Keep extension creation
// and all dependent indexes guarded, including migrations generated after baseline.
export function guardTrgm(sql) {
  // PostgreSQL checks database CREATE even for CREATE SCHEMA IF NOT EXISTS
  // when public already exists. A restricted schema owner must still migrate.
  sql = sql.replace('CREATE SCHEMA IF NOT EXISTS "public";', () => `DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'public') THEN
    CREATE SCHEMA "public";
  END IF;
END $$;`);
  const indexes = [];
  sql = sql.replace(/CREATE (?:UNIQUE )?INDEX[^;]*gin_trgm_ops[^;]*;/g, (statement) => {
    indexes.push(statement.replace('CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS '));
    return '';
  });
  if (!indexes.length) return sql;
  return `DO $$ BEGIN
  CREATE EXTENSION IF NOT EXISTS pg_trgm;
EXCEPTION WHEN insufficient_privilege OR undefined_file OR feature_not_supported THEN
  RAISE NOTICE 'pg_trgm unavailable';
END $$;
\n${sql}\nDO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm') THEN
    ${indexes.join('\n    ')}
  END IF;
END $$;
`;
}

export function migrationNames(root, provider) {
  return readdirSync(`${root}/${provider}`, { withFileTypes: true })
    .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
}
export function assertParity(root = 'prisma/migrations') {
  if (JSON.stringify(migrationNames(root, 'sqlite')) !== JSON.stringify(migrationNames(root, 'postgresql'))) {
    throw new Error('Migration provider parity failed: add the same migration name for both providers');
  }
}

export function assertSafeSql(sql, file) {
  // Strip comments before scanning SQL; keep Prisma's RedefineTables sentinel.
  const code = sql.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--[^\n]*/g, '');
  const destructive = /\bDROP\s+(?:TABLE|COLUMN|INDEX|SCHEMA|TYPE|VIEW|TRIGGER|EXTENSION|CONSTRAINT|SEQUENCE|FUNCTION)\b|\bALTER\s+TABLE\b[^;]*\bDROP\b|\bALTER\s+COLUMN\s+"?\w+"?\s+(?:SET\s+DATA\s+)?TYPE\b|\bALTER\s+TYPE\b|\bTRUNCATE\b|\bDELETE\s+FROM\b|\bUPDATE\s+"?\w+"?\s+SET\b|\bRENAME\s+(?:COLUMN|TO)\b/i.test(code)
    || /RedefineTables/.test(sql);
  if (destructive && !/^[ \t]*-- ff:allow-destructive[ \t]+\S[^\n]*$/m.test(sql)) {
    throw new Error(`${file}: destructive SQL needs -- ff:allow-destructive <reason>`);
  }
  // Every trigram index must be inside an extension-existence DO block.
  const withoutGuards = code.replace(/DO\s+\$\$\s*BEGIN\s+IF EXISTS\s*\(SELECT 1 FROM pg_extension WHERE extname\s*=\s*'pg_trgm'\)\s*THEN[\s\S]*?END IF;\s*END\s*\$\$;/gi, '');
  if (/gin_trgm_ops/i.test(withoutGuards)) throw new Error(`${file}: unguarded gin_trgm_ops`);
}

// The Postgres trigram index swap (Article_*_trgm_idx -> ArticleSearch_*_trgm_idx) is done by the
// app in the background with CREATE/DROP INDEX CONCURRENTLY (lib/search-indexes.ts), not by the
// migration, on populated databases. Until it finishes, the startup drift check sees exactly these
// statements; anything else in the diff is real drift.
const SEARCH_COLUMNS = '(title|content|excerpt|author|entities)';
const PENDING_SWAP = [
  new RegExp(`^DROP INDEX "Article_${SEARCH_COLUMNS}_trgm_idx"$`),
  new RegExp(`^CREATE INDEX "ArticleSearch_${SEARCH_COLUMNS}_trgm_idx" ON "ArticleSearch" USING GIN \\("\\1" gin_trgm_ops\\)$`),
];
/** True when a non-empty `migrate diff --script` consists only of the pending search index swap. */
export function isPendingSearchIndexSwap(sql) {
  const statements = sql.replace(/--[^\n]*/g, '').split(';').map((s) => s.replace(/\s+/g, ' ').trim()).filter(Boolean);
  return statements.length > 0 && statements.every((s) => PENDING_SWAP.some((re) => re.test(s)));
}

// ── Pure-DDL allowlist (startup adoption of db-push databases, scripts/db-migrate.mjs) ──
// A migration may be marked applied WITHOUT running it only if pushing the schema does
// exactly what the migration would do: plain object creation. The SQL is tokenized
// (quote/comment/dollar-quote aware), split on top-level `;`, and every statement must
// fit a small grammar:
//   CREATE TABLE [IF NOT EXISTS] name (column defs | PRIMARY KEY/UNIQUE/FOREIGN KEY constraints)
//   CREATE [UNIQUE] INDEX [IF NOT EXISTS] name ON name [USING method] (columns)
//   CREATE TYPE name AS ENUM ('a', ...)
//   ALTER TABLE name ADD COLUMN ... | ADD CONSTRAINT name FOREIGN KEY ... | UNIQUE (...)  [, ...]
//   DO $$ ... $$  only the exact pg_trgm guard blocks generated by guardTrgm()
// Column DEFAULTs must be literals ('x', 1, -1.5, true/false, NULL, CURRENT_TIMESTAMP, now(),
// literal::type, ARRAY[literals]::type). CHECK, GENERATED, COLLATE, functions, any DML,
// drops/renames/type changes, PRAGMA, unknown tokens and unterminated quotes are violations,
// even with `-- ff:allow-destructive`.
const ALLOWED_DO_BLOCKS = [
  // guardTrgm(): create the extension, tolerate missing privileges
  /^DO \$\$ BEGIN CREATE EXTENSION IF NOT EXISTS pg_trgm; EXCEPTION WHEN insufficient_privilege OR undefined_file OR feature_not_supported THEN RAISE NOTICE 'pg_trgm unavailable'; END \$\$$/,
  // guardTrgm(): trigram indexes only when the extension exists
  /^DO \$\$ BEGIN IF EXISTS \(SELECT 1 FROM pg_extension WHERE extname = 'pg_trgm'\) THEN (?:CREATE INDEX IF NOT EXISTS "\w+" ON "\w+" USING GIN \("\w+" gin_trgm_ops\); )+END IF; END \$\$$/,
  // guardTrgm(): restricted-role-safe CREATE SCHEMA
  /^DO \$\$ BEGIN IF NOT EXISTS \(SELECT 1 FROM pg_namespace WHERE nspname = '\w+'\) THEN CREATE SCHEMA "\w+"; END IF; END \$\$$/,
];
const TYPE_WORDS = new Set(['TEXT', 'INTEGER', 'INT', 'BIGINT', 'SMALLINT', 'BOOLEAN', 'DATETIME', 'TIMESTAMP',
  'TIMESTAMPTZ', 'DATE', 'TIME', 'DOUBLE', 'REAL', 'DECIMAL', 'NUMERIC', 'JSONB', 'JSON', 'BYTEA', 'BLOB', 'UUID',
  'VARCHAR', 'CHAR', 'SERIAL', 'BIGSERIAL', 'FLOAT', 'CITEXT']);
const INDEX_METHODS = new Set(['GIN', 'BTREE', 'HASH', 'GIST', 'BRIN']);
const OPCLASSES = new Set(['GIN_TRGM_OPS']);

class SqlViolation extends Error {}
const bad = (message) => { throw new SqlViolation(message); };

/** Quote/comment/dollar-quote aware tokenizer. Comments are dropped. Throws SqlViolation. @param {string} sql */
export function tokenizeSql(sql) {
  const tokens = [];
  let i = 0;
  const push = (type, start, end, value) => tokens.push({ type, start, end, value, text: sql.slice(start, end) });
  while (i < sql.length) {
    const c = sql[i];
    if (/\s/.test(c)) { i++; continue; }
    if (c === '-' && sql[i + 1] === '-') { const nl = sql.indexOf('\n', i); i = nl < 0 ? sql.length : nl + 1; continue; }
    if (c === '/' && sql[i + 1] === '*') {
      const end = sql.indexOf('*/', i + 2);
      if (end < 0) bad('unterminated /* comment');
      // Postgres nests block comments, SQLite does not: ambiguous, so never allowed.
      if (sql.slice(i + 2, end).includes('/*')) bad('nested /* comment');
      i = end + 2; continue;
    }
    if (c === "'" || c === '"') {
      let j = i + 1;
      for (;;) {
        const k = sql.indexOf(c, j);
        if (k < 0) bad(`unterminated ${c === "'" ? 'string' : 'quoted identifier'}`);
        if (sql[k + 1] === c) { j = k + 2; continue; }
        j = k + 1; break;
      }
      push(c === "'" ? 'str' : 'ident', i, j, sql.slice(i + 1, j - 1).split(c + c).join(c));
      i = j; continue;
    }
    if (c === '$') {
      const m = /^\$([A-Za-z_][A-Za-z0-9_]*)?\$/.exec(sql.slice(i));
      if (!m) { push('other', i, i + 1, c); i++; continue; }
      const end = sql.indexOf(m[0], i + m[0].length);
      if (end < 0) bad(`unterminated dollar quote ${m[0]}`);
      push('dollar', i, end + m[0].length, sql.slice(i + m[0].length, end));
      i = end + m[0].length; continue;
    }
    if (/[A-Za-z_]/.test(c)) {
      const m = /^[A-Za-z_][A-Za-z0-9_]*/.exec(sql.slice(i));
      push('word', i, i + m[0].length, m[0].toUpperCase());
      i += m[0].length; continue;
    }
    if (/[0-9]/.test(c)) {
      const m = /^[0-9]+(?:\.[0-9]+)?/.exec(sql.slice(i));
      if (/[A-Za-z_]/.test(sql[i + m[0].length] ?? '')) bad('malformed number');
      push('num', i, i + m[0].length, m[0]);
      i += m[0].length; continue;
    }
    if (c === ':' && sql[i + 1] === ':') { push('punct', i, i + 2, '::'); i += 2; continue; }
    if ('(),;.[]-'.includes(c)) { push('punct', i, i + 1, c); i++; continue; }
    // Operators etc.: never valid in the allowed grammar, rejected per statement.
    push('other', i, i + 1, c); i++;
  }
  return tokens;
}

/** Split tokens into statements on top-level `;` (quotes/dollar quotes are single tokens). */
function splitStatements(tokens) {
  const statements = [];
  let current = [];
  for (const t of tokens) {
    if (t.type === 'punct' && t.value === ';') { if (current.length) statements.push(current); current = []; } else current.push(t);
  }
  if (current.length) statements.push(current);
  return statements;
}

class Cursor {
  constructor(tokens) { this.t = tokens; this.i = 0; }
  peek(o = 0) { return this.t[this.i + o]; }
  done() { return this.i >= this.t.length; }
  isWord(...words) { const t = this.peek(); return t?.type === 'word' && words.includes(t.value); }
  isPunct(p) { const t = this.peek(); return t?.type === 'punct' && t.value === p; }
  word(...words) { if (!this.isWord(...words)) bad(`expected ${words.join('|')} at ${this.where()}`); return this.t[this.i++].value; }
  punct(p) { if (!this.isPunct(p)) bad(`expected "${p}" at ${this.where()}`); this.i++; }
  optWord(...words) { if (this.isWord(...words)) { this.i++; return true; } return false; }
  optPunct(p) { if (this.isPunct(p)) { this.i++; return true; } return false; }
  where() { const t = this.peek(); return t ? JSON.stringify(t.text) : 'end of statement'; }
  // Object names must be quoted identifiers (Prisma always quotes), optionally schema-qualified.
  name() {
    if (this.peek()?.type !== 'ident') bad(`expected a quoted name at ${this.where()}`);
    this.i++;
    if (this.isPunct('.') && this.peek(1)?.type === 'ident') this.i += 2;
  }
  end() { if (!this.done()) bad(`unexpected ${this.where()}`); }
}

function nameList(c, { index = false } = {}) {
  c.punct('(');
  do {
    c.name();
    if (index) {
      if (c.peek()?.type === 'word' && OPCLASSES.has(c.peek().value)) c.i++;
      c.optWord('ASC', 'DESC');
    }
  } while (c.optPunct(','));
  c.punct(')');
}

function typeName(c) {
  if (c.peek()?.type === 'ident') c.name(); // enum type
  else {
    const w = c.peek();
    if (w?.type !== 'word' || !TYPE_WORDS.has(w.value)) bad(`unsupported type ${c.where()}`);
    c.i++;
    if (w.value === 'DOUBLE') c.word('PRECISION');
    if (c.optPunct('(')) {
      if (c.peek()?.type !== 'num') bad(`type arguments must be numbers at ${c.where()}`);
      c.i++;
      if (c.optPunct(',')) { if (c.peek()?.type !== 'num') bad('type arguments must be numbers'); c.i++; }
      c.punct(')');
    }
    if (c.isWord('WITH', 'WITHOUT')) { c.i++; c.word('TIME'); c.word('ZONE'); }
  }
  while (c.optPunct('[')) c.punct(']');
}

function literal(c) {
  const t = c.peek();
  if (t?.type === 'str' || t?.type === 'num') { c.i++; return true; }
  if (t?.type === 'punct' && t.value === '-' && c.peek(1)?.type === 'num') { c.i += 2; return true; }
  if (c.optWord('TRUE', 'FALSE', 'NULL')) return true;
  return false;
}

function defaultExpression(c) {
  if (c.optWord('CURRENT_TIMESTAMP')) return;
  if (c.isWord('NOW')) { c.i++; c.punct('('); c.punct(')'); return; }
  if (c.optWord('ARRAY')) {
    c.punct('[');
    if (!c.isPunct(']')) { do { if (!literal(c)) bad(`ARRAY default must contain literals at ${c.where()}`); } while (c.optPunct(',')); }
    c.punct(']');
  } else if (!literal(c)) {
    bad(`DEFAULT must be a literal, CURRENT_TIMESTAMP or now() at ${c.where()}`);
  }
  if (c.optPunct('::')) typeName(c);
}

function referentialActions(c) {
  while (c.optWord('ON')) {
    c.word('DELETE', 'UPDATE');
    if (c.optWord('SET')) c.word('NULL', 'DEFAULT');
    else if (c.optWord('NO')) c.word('ACTION');
    else c.word('CASCADE', 'RESTRICT');
  }
}

function columnDefinition(c) {
  c.name();
  typeName(c);
  while (!c.done() && !c.isPunct(',') && !c.isPunct(')')) {
    if (c.optWord('NOT')) c.word('NULL');
    else if (c.optWord('NULL', 'UNIQUE', 'AUTOINCREMENT')) { /* ok */ }
    else if (c.optWord('PRIMARY')) { c.word('KEY'); c.optWord('ASC', 'DESC'); c.optWord('AUTOINCREMENT'); }
    else if (c.optWord('DEFAULT')) defaultExpression(c);
    else if (c.optWord('REFERENCES')) { c.name(); if (c.isPunct('(')) nameList(c); referentialActions(c); }
    else if (c.optWord('CONSTRAINT')) c.name();
    else bad(`unsupported column clause ${c.where()}`);
  }
}

function tableConstraint(c) {
  if (c.optWord('PRIMARY')) { c.word('KEY'); nameList(c, { index: true }); }
  else if (c.optWord('UNIQUE')) nameList(c, { index: true });
  else { c.word('FOREIGN'); c.word('KEY'); nameList(c); c.word('REFERENCES'); c.name(); nameList(c); referentialActions(c); }
}

function createTable(c) {
  if (c.optWord('IF')) { c.word('NOT'); c.word('EXISTS'); }
  c.name();
  c.punct('(');
  do {
    if (c.optWord('CONSTRAINT')) { c.name(); tableConstraint(c); }
    else if (c.isWord('PRIMARY', 'UNIQUE', 'FOREIGN')) tableConstraint(c);
    else columnDefinition(c);
  } while (c.optPunct(','));
  c.punct(')');
  c.end();
}

function createIndex(c) {
  c.word('INDEX');
  if (c.optWord('IF')) { c.word('NOT'); c.word('EXISTS'); }
  c.name();
  c.word('ON');
  c.optWord('ONLY');
  c.name();
  if (c.optWord('USING')) { const t = c.peek(); if (t?.type !== 'word' || !INDEX_METHODS.has(t.value)) bad(`unsupported index method ${c.where()}`); c.i++; }
  nameList(c, { index: true });
  c.end();
}

function alterTable(c) {
  c.optWord('ONLY');
  c.name();
  do {
    c.word('ADD');
    if (c.optWord('COLUMN')) { if (c.optWord('IF')) { c.word('NOT'); c.word('EXISTS'); } columnDefinition(c); }
    else { c.word('CONSTRAINT'); c.name(); if (c.isWord('PRIMARY')) bad('ADD PRIMARY KEY is not allowed'); tableConstraint(c); }
  } while (c.optPunct(','));
  c.end();
}

function checkStatement(tokens) {
  const c = new Cursor(tokens);
  if (c.isWord('DO')) {
    if (tokens.some((t) => t.type === 'other')) bad('unexpected characters in DO statement');
    c.i++;
    const body = c.peek();
    if (body?.type !== 'dollar' || body.text.slice(0, 2) !== '$$') bad('DO block must be $$-quoted');
    c.i++;
    c.end();
    const flat = `DO $$ ${body.value.replace(/\s+/g, ' ').trim()} $$`;
    if (!ALLOWED_DO_BLOCKS.some((re) => re.test(flat))) bad('DO block is not one of the generated pg_trgm guards');
    return;
  }
  for (const t of tokens) {
    if (t.type === 'dollar') bad('dollar-quoted text outside an allowed DO block');
    if (t.type === 'other') bad(`unexpected character ${JSON.stringify(t.text)}`);
  }
  c.word('CREATE', 'ALTER');
  if (tokens[0].value === 'ALTER') { c.word('TABLE'); return alterTable(c); }
  if (c.optWord('TABLE')) return createTable(c);
  if (c.optWord('TYPE')) {
    c.name(); c.word('AS'); c.word('ENUM'); c.punct('(');
    do { if (c.peek()?.type !== 'str') bad('ENUM values must be strings'); c.i++; } while (c.optPunct(','));
    c.punct(')');
    return c.end();
  }
  c.optWord('UNIQUE');
  return createIndex(c);
}

/** Returns the reasons `sql` is not pure DDL (empty array = allowed). @param {string} sql */
export function pureDdlViolations(sql) {
  const problems = [];
  // Prisma's SQLite table rebuild marker (copy rows, drop, rename) is never plain DDL.
  if (/RedefineTables/.test(sql)) problems.push('RedefineTables (SQLite table rebuild)');
  let tokens;
  try {
    tokens = tokenizeSql(sql);
  } catch (error) {
    if (!(error instanceof SqlViolation)) throw error;
    return [...problems, `cannot tokenize: ${error.message}`];
  }
  for (const statement of splitStatements(tokens)) {
    try {
      checkStatement(statement);
    } catch (error) {
      if (!(error instanceof SqlViolation)) throw error;
      const text = sql.slice(statement[0].start, statement.at(-1).end).replace(/\s+/g, ' ');
      problems.push(`${text.slice(0, 120)}${text.length > 120 ? '…' : ''} (${error.message})`);
    }
  }
  return problems;
}

/** @param {string} sql @param {string} file */
export function assertPureDdl(sql, file) {
  const problems = pureDdlViolations(sql);
  if (problems.length) throw new Error(`${file}: not pure DDL (cannot be adopted without running it):\n  - ${problems.join('\n  - ')}`);
}
